"""As-mixed cue sheet, shot by shot, from what render.py actually played (audio/notes.json, audio/events.json) and the
measured loudness (audio/analysis.json). Prints a Markdown table.
Usage (project root):  python -I audio/tools/cuesheet.py            # print
                       python -I audio/tools/cuesheet.py --write    # replace the '## As mixed' part of audio/cuesheet.md
"""
import os, sys, json
from collections import defaultdict

sys.stdout.reconfigure(encoding='utf-8')
A = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
notes = json.load(open(os.path.join(A, 'notes.json')))
events = json.load(open(os.path.join(A, 'events.json')))
an = json.load(open(os.path.join(A, 'analysis.json')))
TL = json.load(open(os.path.join(A, 'cache', 'timeline.json')))
NAMES = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'G#', 'A', 'Bb', 'B']
INST = {'vn': 'vln', 'va': 'vla', 'vc': 'vc', 'cb': 'cb', 'hn': 'horns', 'tb': 'trb', 'tu': 'tuba', 'tp': 'tpt',
        'fl': 'flute', 'ob': 'oboe', 'cl': 'clar', 'bn': 'bsn', 'harp': 'harp', 'glass': 'glass', 'glock': 'glock', 'timp': 'timpani'}
ART = {'sus': '', 'trem': ' trem', 'spic': ' spicc', 'pizz': ' pizz', 'nv': ''}
SKIP = {'fade', 'spread', 'put', 'sound', 'add', 'tooth_click', 'panel_knock', 'timp', 'boot_step'}


def nname(m):
    return f'{NAMES[m % 12]}{m // 12 - 1}'


def inst_name(k):
    head, _, tail = k.partition('_')
    return INST.get(head, head) + ART.get(tail, '' if not tail else ' ' + tail)


def table():
    rows = ['| shot | sec | max mom. LUFS | music (instrument: pitches) | sound (**bold** = starts in the shot, @time) |', '|---|---|---|---|---|']
    mom = an.get('momentary_max_per_shot', {})
    for s in TL['SHOTS']:
        a, b = s['start'], s['end']
        mus = defaultdict(set)
        for n in notes:
            if n['t'] < b and n['t'] + n['dur'] > a:
                mus[inst_name(n['inst'])].add(n['midi'])
        order = sorted(mus.items(), key=lambda kv: min(kv[1]))
        mtxt = '; '.join(k + ' ' + ' '.join(nname(m) for m in sorted(v)) for k, v in order) or '(no music)'
        fx, seen = [], set()
        for t0, t1, bus, lab, lvl in sorted(events):
            if lab in SKIP or not (t0 < b and t1 > a):
                continue
            starts = a <= t0 < b
            key = (lab, starts)
            if lab in seen and not starts:
                continue
            seen.add(lab)
            fx.append(f'**{lab}** @{t0:.2f}' if starts else lab)
        rows.append(f"| {s['id']} {s['name']} | {a:g}-{b:g} | {mom.get(s['id'], '')} | {mtxt} | {', '.join(fx)} |")
    return '\n'.join(rows)


if __name__ == '__main__':
    tab = table()
    if '--write' in sys.argv:
        p = os.path.join(A, 'cuesheet.md')
        s = open(p, encoding='utf-8').read()
        if '## As mixed' in s:
            s = s[:s.index('## As mixed')]
        s = s.rstrip() + '\n\n## As mixed\nGenerated by `audio/tools/cuesheet.py --write` from what the renderer played and the measured levels ' \
            '(storm beds, gear clicks and long ambiences are omitted; see render.py).\n\n' + tab + '\n'
        open(p, 'w', encoding='utf-8').write(s)
        print('wrote audio/cuesheet.md')
    else:
        print(tab)
